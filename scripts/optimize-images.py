#!/usr/bin/env python3
"""Generate content-addressed WebP derivatives without modifying source photos or JSON.
Requires Pillow with WebP support: python -m pip install Pillow
Run again after importing photos and before building/deploying the storefront.
"""

from pathlib import Path
import hashlib
import json
import sys

try:
    from PIL import Image, ImageOps, features
except ImportError:
    sys.exit("Pillow is required. Install it with: python -m pip install Pillow")
if not features.check("webp"):
    sys.exit(
        "The installed Pillow does not support WebP. Install an official Pillow wheel."
    )

root = Path(__file__).resolve().parents[1]
public = root / "public"
source = public / "images"
target = source / "optimized"
manifest_file = root / "src" / "lib" / "optimized-images.generated.js"
target.mkdir(parents=True, exist_ok=True)
manifest = {}
failures = []
for path in sorted(source.rglob("*")):
    if (
        not path.is_file()
        or target in path.parents
        or path.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}
    ):
        continue
    try:
        digest = hashlib.sha256(
            path.read_bytes() + b"chronova-webp-v1-q80"
        ).hexdigest()[:20]
        with Image.open(path) as original:
            if original.format == "WEBP" and getattr(original, "is_animated", False):
                continue  # Keep animated WebP intact. JPEG/MPO uses its browser-visible first frame.
            image = ImageOps.exif_transpose(original)
            image.load()
            if image.mode not in ("RGB", "RGBA"):
                image = image.convert("RGBA" if "transparency" in image.info else "RGB")
            variants = []
            for max_width in (640, 1600):
                width = min(image.width, max_width)
                if variants and variants[-1]["width"] == width:
                    continue
                filename = f"{digest}-{width}.webp"
                out = target / filename
                if not out.exists():
                    height = max(1, round(image.height * width / image.width))
                    resized = (
                        image.resize((width, height), Image.Resampling.LANCZOS)
                        if width != image.width
                        else image
                    )
                    resized.save(out, "WEBP", quality=80, method=5)
                variants.append(
                    {"width": width, "src": f"/images/optimized/{filename}"}
                )
            manifest["/" + path.relative_to(public).as_posix()] = variants
    except Exception as exc:
        failures.append(f"{path.relative_to(root)}: {exc}")
if failures:
    for failure in failures:
        print("Could not optimize:", failure, file=sys.stderr)
    sys.exit("Image optimization failed; existing manifest has not been replaced.")
manifest_file.write_text(
    "// Generated by scripts/optimize-images.py. Do not edit by hand.\nexport default "
    + json.dumps(manifest, ensure_ascii=True, separators=(",", ":"))
    + ";\n",
    encoding="utf-8",
)
print(f"Optimized {len(manifest)} source images. Originals and JSON were not modified.")
